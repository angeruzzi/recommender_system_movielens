        "def precision_at_k(recommended_items, relevant_items, k=10):\n",
        "    \"\"\"\n",
        "    Calcula Precision@K.\n",
        "\n",
        "    Parameters\n",
        "    ----------\n",
        "    recommended_items : list\n",
        "        Lista ordenada de itens recomendados.\n",
        "\n",
        "    relevant_items : set or list\n",
        "        Conjunto de itens relevantes para o usuário.\n",
        "\n",
        "    k : int, default=10\n",
        "        Número máximo de recomendações consideradas.\n",
        "\n",
        "    Returns\n",
        "    -------\n",
        "    float\n",
        "        Precision@K.\n",
        "    \"\"\"\n",
        "    if k <= 0:\n",
        "        return 0.0\n",
        "\n",
        "    recommended_k = recommended_items[:k]\n",
        "\n",
        "    hits = len(\n",
        "        set(recommended_k) & set(relevant_items)\n",
        "    )\n",
        "\n",
        "    return hits / k\n",
        "\n",
        "\n",
        "def recall_at_k(recommended_items, relevant_items, k=10):\n",
        "    \"\"\"\n",
        "    Calcula Recall@K.\n",
        "\n",
        "    Parameters\n",
        "    ----------\n",
        "    recommended_items : list\n",
        "        Lista ordenada de itens recomendados.\n",
        "\n",
        "    relevant_items : set or list\n",
        "        Conjunto de itens relevantes para o usuário.\n",
        "\n",
        "    k : int, default=10\n",
        "        Número máximo de recomendações consideradas.\n",
        "\n",
        "    Returns\n",
        "    -------\n",
        "    float\n",
        "        Recall@K.\n",
        "    \"\"\"\n",
        "    relevant_items = set(relevant_items)\n",
        "\n",
        "    if len(relevant_items) == 0:\n",
        "        return 0.0\n",
        "\n",
        "    recommended_k = recommended_items[:k]\n",
        "\n",
        "    hits = len(\n",
        "        set(recommended_k) & relevant_items\n",
        "    )\n",
        "\n",
        "    return hits / len(relevant_items)\n",
