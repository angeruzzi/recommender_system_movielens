        "def ndcg_at_k(recommended_items, relevant_items, k=10):\n",
        "    \"\"\"\n",
        "    Calcula NDCG@K utilizando relevância binária.\n",
        "\n",
        "    Itens relevantes posicionados no início do ranking\n",
        "    recebem maior peso.\n",
        "\n",
        "    Parameters\n",
        "    ----------\n",
        "    recommended_items : list\n",
        "        Lista ordenada de itens recomendados.\n",
        "\n",
        "    relevant_items : set or list\n",
        "        Conjunto de itens relevantes para o usuário.\n",
        "\n",
        "    k : int, default=10\n",
        "        Número máximo de recomendações consideradas.\n",
        "\n",
        "    Returns\n",
        "    -------\n",
        "    float\n",
        "        NDCG@K.\n",
        "    \"\"\"\n",
        "    relevant_items = set(relevant_items)\n",
        "\n",
        "    if len(relevant_items) == 0 or k <= 0:\n",
        "        return 0.0\n",
        "\n",
        "    recommended_k = recommended_items[:k]\n",
        "\n",
        "    dcg = 0.0\n",
        "\n",
        "    for position, item_id in enumerate(\n",
        "        recommended_k,\n",
        "        start=1\n",
        "    ):\n",
        "        if item_id in relevant_items:\n",
        "            dcg += 1 / np.log2(position + 1)\n",
        "\n",
        "    ideal_hits = min(\n",
        "        len(relevant_items),\n",
        "        k\n",
        "    )\n",
        "\n",
        "    idcg = sum(\n",
        "        1 / np.log2(position + 1)\n",
        "        for position in range(1, ideal_hits + 1)\n",
        "    )\n",
        "\n",
        "    if idcg == 0:\n",
        "        return 0.0\n",
        "\n",
        "    return dcg / idcg\n",
